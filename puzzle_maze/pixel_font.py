def render(text,size,color):
    factor=max(1,size//8)
    surface=pygame.Surface((max(1,len(text)*6-1)*factor,7*factor),pygame.SRCALPHA)
    for index,char in enumerate(text.upper()):
        rows=ROWS.get(char,ROWS['?'])
        for y in range(7):
            bits=int(rows[y*2:y*2+2],16)
            for x in range(5):
                if bits&(1<<(4-x)):pygame.draw.rect(surface,color,((index*6+x)*factor,y*factor,factor,factor))
    return surface
